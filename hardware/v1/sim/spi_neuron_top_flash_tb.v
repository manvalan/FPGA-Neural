// master bit-banging tasks copied verbatim from there), driving the
// FULL integrated top level -- spi_slave + spi_engine + graph_engine
// + flash_slot_manager (-> flash_copy_engine -> spi_flash_master) +
// mem_arbiter + int8_memory_access + memory_interface +
// psram_controller + psram_model + flash_model -- purely over
// simulated host SPI and simulated flash SPI.
//
//   TEST 1: FLASH_ERASE + FLASH_WRITE_BLOCK + FLASH_READ_BLOCK
//     opcode-level smoke test over real SPI framing (deep
//     correctness of these primitives already covered by
//     sim/flash_copy_engine_erase_tb.v and
//     sim/flash_slot_manager_raw_tb.v -- this proves the SPI byte
//     framing in spi_engine.v decodes them correctly, which those
//     module-level tests cannot).
//   TEST 2: CAT_WRITE_SLOT + CAT_READ + CAT_INSPECT over real SPI.
//   TEST 3 (adversarial §A.3): LOAD_SLOT on a never-saved slot ->
//     STATUS.bit3 (flash_err) observed over real SPI.
//   TEST 4 (the phase-plan's explicit §6 end-to-end requirement):
//     netasm -> WRITE_RAM -> SAVE_SLOT -> (PSRAM region overwritten
//     with garbage, proving the reload is real) -> LOAD_SLOT ->
//     RUN_NETWORK -> READ_RAM matches the hand-computed expected
//     output (126), the SAME independently-derived value already
//     used in sim/graph_engine_tb.v / sim/spi_neuron_top_graph_tb.v
//     (spec §3's worked example, x=[10,1,4,0] -> n4=49, n5=126) --
//     not re-derived here, reused as the existing independent
//     oracle. The exact WRITE_RAM/SET_BASE/RUN_NETWORK byte sequence
//     below was generated by netasm itself (not hand-typed):
//       python3 tools/netasm/cli.py tools/netasm/examples/graph_example.netasm \
//         -o /tmp/netasm_out/graph --table-base 0x000000 \
//         --edges-base 0x000100 --x-base 0x000400 --out-base 0x000500
//     (see that command's own .debug.txt output, quoted inline below
//     at each step for traceability).
